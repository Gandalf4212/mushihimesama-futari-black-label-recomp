#!/usr/bin/env python3
"""Generate sh3_interp.inc (interpreter handlers + decode table) from isa.py.
Usage: gen_interp.py <out.inc>"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from isa import ISA, build_decode_table

def field(pat, ch):
    idx = [k for k, c in enumerate(pat) if c == ch]
    if not idx: return None
    return 15 - idx[-1], (1 << len(idx)) - 1

def handler(i, pat, mn, kind, body):
    lines = [f'/* {mn} */', f'static void op_{i}(SH3 *s, uint16_t op) {{', '    uint32_t PC = s->pc; (void)PC; (void)op;']
    for ch, names in (('n', ['n']), ('m', ['m']), ('i', ['IMM']), ('d', ['D4', 'D8', 'D12'])):
        f = field(pat, ch)
        if not f: continue
        sh, mask = f
        if ch == 'd':
            name = {15: 'D4', 255: 'D8', 4095: 'D12'}[mask]
            lines.append(f'    uint32_t {name} = (op >> {sh}) & {mask};')
        elif ch == 'i':
            lines.append(f'    uint32_t IMM = (op >> {sh}) & {mask}; int32_t SIMM = (int8_t)IMM; (void)SIMM;')
        else:
            lines.append(f'    int {ch} = (op >> {sh}) & {mask}; (void){ch};')
    lines.append('    ' + body)
    lines.append('}')
    return '\n'.join(lines)

def main():
    out = sys.argv[1]
    table = build_decode_table()
    parts = ['/* GENERATED by gen_interp.py from isa.py. Do not edit. */',
             '#define JUMP(t) (s->next_pc = (t))',
             '#define DELAY(t) (s->slot_target = (t), s->has_slot = 1)',
             '#define TRAPA(i) (s->trap = (int)(i) + 1)',
             '#define SLEEP() (s->sleeping = 1)',
             'static void op_illegal(SH3 *s, uint16_t op) { fprintf(stderr, "illegal op %04x at %08x\\n", op, s->pc); abort(); }']
    for i, (pat, mn, kind, body) in enumerate(ISA):
        parts.append(handler(i, pat, mn, kind, body))
    parts.append('static void (*sh3_ops[65536])(SH3 *, uint16_t);')
    parts.append('static const char *sh3_names[%d] = {%s};' % (len(ISA), ', '.join('"%s"' % e[1] for e in ISA)))
    # compact decode: list of (mask, value, index), applied at init
    parts.append('static const struct { uint16_t mask, val; int16_t idx; } sh3_pats[] = {')
    for i, (pat, *_r) in enumerate(ISA):
        mask = int(''.join('1' if c in '01' else '0' for c in pat), 2)
        val = int(''.join('1' if c == '1' else '0' for c in pat), 2)
        parts.append(f'    {{0x{mask:04x}, 0x{val:04x}, {i}}},')
    parts.append('};')
    parts.append('static void (*const sh3_handlers[])(SH3 *, uint16_t) = {' + ', '.join(f'op_{i}' for i in range(len(ISA))) + '};')
    parts.append('''static int16_t sh3_index[65536];
static void sh3_init_ops(void) {
    for (int op = 0; op < 65536; op++) { sh3_ops[op] = op_illegal; sh3_index[op] = -1; }
    for (unsigned p = 0; p < sizeof sh3_pats / sizeof sh3_pats[0]; p++)
        for (int op = 0; op < 65536; op++)
            if ((op & sh3_pats[p].mask) == sh3_pats[p].val) { sh3_ops[op] = sh3_handlers[sh3_pats[p].idx]; sh3_index[op] = sh3_pats[p].idx; }
}
const char *sh3_mnemonic(uint16_t op) { if (!ops_ready_ext()) sh3_init_ops(); return sh3_index[op] < 0 ? 0 : sh3_names[sh3_index[op]]; }''')
    parts.insert(1, 'static int ops_ready_ext(void);')
    open(out, 'w').write('\n'.join(parts) + '\n')
    print(f'{len(ISA)} instructions, {sum(1 for t in table if t >= 0)} valid opcodes -> {out}')

if __name__ == '__main__':
    main()
