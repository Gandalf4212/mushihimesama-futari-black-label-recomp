#!/usr/bin/env python3
"""Generate isa_table.inc (the isa.py table as C data) for the C translator core/sh3/recomp.c.
Usage: gen_isa_c.py <out.inc>      isa.py stays the single source of truth. GPL-2.0-or-later."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from isa import ISA

KINDS = ['op', 'cbr', 'cbrs', 'br', 'ijmp', 'call', 'icall', 'ret', 'rte', 'trap', 'sleep']


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def field(pat, ch):
    idx = [k for k, c in enumerate(pat) if c == ch]
    if not idx:
        return -1, 0
    return 15 - idx[-1], (1 << len(idx)) - 1


out = ['/* GENERATED by core/sh3/gen_isa_c.py from isa.py. */',
       'enum { ' + ', '.join(f'K_{k.upper()}' for k in KINDS) + ' };',
       'typedef struct { uint16_t fixed, val; const char *mn; int kind; const char *body;',
       '                 int8_t sh[4]; uint16_t mask[4]; } IsaEntry;   /* fields n, m, i, d */',
       'static const IsaEntry ISA[] = {']
for pat, mn, kind, body in ISA:
    fixed = int(''.join('1' if c in '01' else '0' for c in pat), 2)
    val = int(''.join('1' if c == '1' else '0' for c in pat), 2)
    f = [field(pat, ch) for ch in 'nmid']
    out.append(f'    {{0x{fixed:04X}, 0x{val:04X}, {cstr(mn)}, K_{kind.upper()}, {cstr(body)}, '
               f'{{{", ".join(str(s) for s, _ in f)}}}, {{{", ".join(str(m) for _, m in f)}}}}},')
out.append('};')
out.append(f'#define ISA_COUNT {len(ISA)}')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
